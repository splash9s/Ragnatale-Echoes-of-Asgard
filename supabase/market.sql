-- Ragnatale: auction market (gear only, gold). Run once in the SQL editor, after schema.sql and friends.sql
-- (uses mail and profiles). Rules: level 10+, Gmail-linked accounts only, 6h / 12h / 24h auctions,
-- listing fee 5% of the start price (paid when listed), sale fee 5% of the final price (taken from the seller).
-- Outbid gold and won or returned items are sent by mail, and the game claims them like any other mail.

create table if not exists public.auction_listings (
    id bigint generated by default as identity primary key,
    seller_id uuid not null references auth.users(id) on delete cascade,
    seller_name text not null default 'Hero',
    item jsonb not null,
    category text not null,
    start_price bigint not null check (start_price > 0),
    current_price bigint not null,
    top_bidder_id uuid references auth.users(id) on delete set null,
    top_bidder_name text,
    bid_count int not null default 0,
    listing_fee bigint not null default 0,
    duration_hours int not null,
    ends_at timestamptz not null,
    status text not null default 'open' check (status in ('open', 'sold', 'expired', 'cancelled')),
    created_at timestamptz not null default now()
);
create index if not exists auction_listings_open_idx on public.auction_listings (status, ends_at);

-- No direct table access: everything goes through the functions below
alter table public.auction_listings enable row level security;

-- Shared rules (used by every function)
create or replace function public.market_eligible() returns uuid
language plpgsql security definer set search_path = public as $$
declare
    me uuid := auth.uid();
    lv int;
begin
    if me is null then raise exception 'Sign in first'; end if;
    if coalesce((auth.jwt() ->> 'is_anonymous')::boolean, false) then
        raise exception 'Link a Gmail account in Settings to use the market';
    end if;
    select base_lv into lv from public.profiles where user_id = me;
    if coalesce(lv, 0) < 10 then raise exception 'The market opens at level 10'; end if;
    return me;
end $$;

-- Starts an auction. The client has already checked the gear, the gold for the listing fee and the bag,
-- and removes the item from the bag only after this succeeds.
create or replace function public.auction_create(p_item jsonb, p_start bigint, p_hours int) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
    me uuid;
    seller text;
    slot text;
    cat text;
    open_count int;
    fee bigint;
    ends timestamptz;
    new_id bigint;
begin
    me := public.market_eligible();
    if p_hours not in (6, 12, 24) then raise exception 'Auction time must be 6, 12 or 24 hours'; end if;
    if p_start is null or p_start < 1 or p_start > 1000000000 then raise exception 'Start price must be 1 to 1,000,000,000 gold'; end if;
    if jsonb_typeof(p_item) <> 'object' or coalesce(p_item->>'name', '') = '' then raise exception 'Invalid item'; end if;
    slot := p_item->>'slot';
    cat := case
        when slot in ('ringLeft', 'ringRight', 'ring') then 'ring'
        when slot in ('weapon', 'shield', 'armor', 'hat', 'midHead', 'mouth', 'garment', 'footgear') then slot
        else null end;
    if cat is null then raise exception 'Only gear can be sold on the market'; end if;

    select count(*) into open_count from public.auction_listings
        where seller_id = me and status = 'open';
    if open_count >= 5 then raise exception 'You can have up to 5 auctions at once'; end if;

    fee := floor(p_start * 5 / 100);
    ends := now() + make_interval(hours => p_hours);
    select name into seller from public.profiles where user_id = me;

    insert into public.auction_listings
        (seller_id, seller_name, item, category, start_price, current_price, listing_fee, duration_hours, ends_at)
    values (me, coalesce(seller, 'Hero'), p_item, cat, p_start, p_start, fee, p_hours, ends)
    returning id into new_id;

    return jsonb_build_object('id', new_id, 'fee', fee, 'ends_at', ends);
end $$;

-- Places a bid. The first bid must be at least the start price; later bids must beat the current price by 5% (at least 1).
-- The bidder's gold is taken by the client after this succeeds. The previous top bidder gets their gold back by mail.
create or replace function public.auction_bid(p_id bigint, p_amount bigint) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
    me uuid;
    l public.auction_listings;
    needed bigint;
    bidder text;
begin
    me := public.market_eligible();
    select * into l from public.auction_listings where id = p_id for update;
    if not found or l.status <> 'open' or l.ends_at <= now() then raise exception 'This auction has ended'; end if;
    if l.seller_id = me then raise exception 'You cannot bid on your own item'; end if;
    if l.top_bidder_id = me then raise exception 'You already have the highest bid'; end if;
    if p_amount is null or p_amount > 1000000000 then raise exception 'Bid is too high'; end if;

    if l.bid_count = 0 then needed := l.start_price;
    else needed := l.current_price + greatest(1, floor(l.current_price * 5 / 100)); end if;
    if p_amount < needed then raise exception 'Bid must be at least % gold', needed; end if;

    if l.top_bidder_id is not null then
        insert into public.mail (recipient_id, title, sender, message, rewards)
        values (l.top_bidder_id, 'Auction Refund', 'Auction House',
                'You were outbid on ' || (l.item->>'name') || '. Your gold is returned.',
                jsonb_build_object('gold', l.current_price));
    end if;

    select name into bidder from public.profiles where user_id = me;
    update public.auction_listings
        set current_price = p_amount, top_bidder_id = me, top_bidder_name = coalesce(bidder, 'Hero'), bid_count = bid_count + 1
        where id = p_id;

    return jsonb_build_object('current_price', p_amount, 'min_next', p_amount + greatest(1, floor(p_amount * 5 / 100)));
end $$;

-- The seller takes an auction back only when nobody has bid. The item comes back by mail.
create or replace function public.auction_cancel(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare
    me uuid := auth.uid();
    l public.auction_listings;
begin
    if me is null then raise exception 'Sign in first'; end if;
    select * into l from public.auction_listings where id = p_id for update;
    if not found or l.seller_id <> me or l.status <> 'open' then raise exception 'Auction not found'; end if;
    if l.bid_count > 0 then raise exception 'You cannot cancel an auction that has bids'; end if;
    update public.auction_listings set status = 'cancelled' where id = p_id;
    insert into public.mail (recipient_id, title, sender, message, rewards)
    values (me, 'Auction Cancelled', 'Auction House', 'Your ' || (l.item->>'name') || ' is back.',
            jsonb_build_object('items', jsonb_build_array(l.item)));
end $$;

-- Ends every auction whose time is up: winners get the item, sellers get the gold (minus the sale fee),
-- and unsold items go back to the seller. Any player can run it when they open the market.
create or replace function public.auction_settle() returns int
language plpgsql security definer set search_path = public as $$
declare
    l public.auction_listings;
    done int := 0;
    fee bigint;
begin
    if auth.uid() is null then raise exception 'Sign in first'; end if;
    for l in select * from public.auction_listings
             where status = 'open' and ends_at <= now()
             for update skip locked loop
        if l.top_bidder_id is not null then
            fee := floor(l.current_price * 5 / 100);
            update public.auction_listings set status = 'sold' where id = l.id;
            insert into public.mail (recipient_id, title, sender, message, rewards)
            values (l.top_bidder_id, 'Auction Won', 'Auction House',
                    'You won the auction for ' || (l.item->>'name') || '.',
                    jsonb_build_object('items', jsonb_build_array(l.item)));
            insert into public.mail (recipient_id, title, sender, message, rewards)
            values (l.seller_id, 'Auction Sold', 'Auction House',
                    l.item->>'name' || ' sold to ' || coalesce(l.top_bidder_name, 'a buyer') || '. Sale fee ' || fee || ' gold.',
                    jsonb_build_object('gold', l.current_price - fee));
        else
            update public.auction_listings set status = 'expired' where id = l.id;
            insert into public.mail (recipient_id, title, sender, message, rewards)
            values (l.seller_id, 'Auction Expired', 'Auction House',
                    'No bids on ' || (l.item->>'name') || '. It is back in your mailbox.',
                    jsonb_build_object('items', jsonb_build_array(l.item)));
        end if;
        done := done + 1;
    end loop;
    return done;
end $$;

-- Open auctions for one category ('all' or a category name), soonest ending first
create or replace function public.auction_browse(p_category text default 'all', p_offset int default 0) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
    me uuid := auth.uid();
    rows jsonb;
begin
    if me is null then raise exception 'Sign in first'; end if;
    select coalesce(jsonb_agg(r order by r.ends_at), '[]'::jsonb) into rows from (
        select id, item, category, seller_name, start_price, current_price, bid_count, top_bidder_name,
               duration_hours, ends_at,
               (seller_id = me) as is_mine, (top_bidder_id = me) as i_lead
        from public.auction_listings
        where status = 'open' and ends_at > now()
          and (p_category is null or p_category = 'all' or category = p_category)
        order by ends_at
        limit 50 offset greatest(0, p_offset)
    ) r;
    return rows;
end $$;

-- My auctions: open ones I am selling, the ones I am leading, and my finished ones from the last 3 days
create or replace function public.auction_mine() returns jsonb
language plpgsql security definer set search_path = public as $$
declare
    me uuid := auth.uid();
    sell_list jsonb;
    lead_list jsonb;
begin
    if me is null then raise exception 'Sign in first'; end if;
    select coalesce(jsonb_agg(r order by r.ends_at desc), '[]'::jsonb) into sell_list from (
        select id, item, category, start_price, current_price, bid_count, top_bidder_name, status, ends_at
        from public.auction_listings
        where seller_id = me and (status = 'open' or created_at > now() - interval '3 days')
        order by ends_at desc limit 30
    ) r;
    select coalesce(jsonb_agg(r order by r.ends_at), '[]'::jsonb) into lead_list from (
        select id, item, category, current_price, ends_at
        from public.auction_listings
        where top_bidder_id = me and status = 'open' and ends_at > now()
        order by ends_at limit 30
    ) r;
    return jsonb_build_object('selling', sell_list, 'leading', lead_list);
end $$;

revoke all on function public.market_eligible() from public, anon;
grant execute on function public.auction_create(jsonb, bigint, int) to authenticated;
grant execute on function public.auction_bid(bigint, bigint) to authenticated;
grant execute on function public.auction_cancel(bigint) to authenticated;
grant execute on function public.auction_settle() to authenticated;
grant execute on function public.auction_browse(text, int) to authenticated;
grant execute on function public.auction_mine() to authenticated;
