-- One save per player (the whole player object as JSON)
create table if not exists public.saves (
    user_id uuid primary key references auth.users(id) on delete cascade,
    data jsonb not null,
    updated_at timestamptz not null default now()
);

-- Mail sent to one player
create table if not exists public.mail (
    id bigint generated by default as identity primary key,
    recipient_id uuid not null references auth.users(id) on delete cascade,
    title text not null default 'Mail',
    sender text not null default 'System',
    message text not null default '',
    rewards jsonb not null default '{}'::jsonb,
    sent_at timestamptz not null default now(),
    claimed_at timestamptz
);

-- Mail sent to every player (stored once)
create table if not exists public.global_mail (
    id bigint generated by default as identity primary key,
    title text not null default 'Mail',
    sender text not null default 'System',
    message text not null default '',
    rewards jsonb not null default '{}'::jsonb,
    sent_at timestamptz not null default now()
);

-- Which player has claimed which global mail
create table if not exists public.global_mail_claims (
    user_id uuid not null references auth.users(id) on delete cascade,
    mail_id bigint not null references public.global_mail(id) on delete cascade,
    claimed_at timestamptz not null default now(),
    primary key (user_id, mail_id)
);

-- Row level security: players only see and change their own rows
alter table public.saves enable row level security;
alter table public.mail enable row level security;
alter table public.global_mail enable row level security;
alter table public.global_mail_claims enable row level security;

drop policy if exists "own save" on public.saves;
create policy "own save" on public.saves for all
    using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "own mail" on public.mail;
create policy "own mail" on public.mail for select
    using (auth.uid() = recipient_id);

drop policy if exists "read global mail" on public.global_mail;
create policy "read global mail" on public.global_mail for select
    to authenticated using (true);

drop policy if exists "own global claims" on public.global_mail_claims;
create policy "own global claims" on public.global_mail_claims for select
    using (auth.uid() = user_id);

-- Claiming goes through functions so players cannot edit rewards or claim twice
create or replace function public.claim_mail(p_id bigint)
returns jsonb language plpgsql security definer set search_path = public as $$
declare r jsonb;
begin
    update public.mail set claimed_at = now()
    where id = p_id and recipient_id = auth.uid() and claimed_at is null
    returning rewards into r;
    if r is null then raise exception 'mail not claimable'; end if;
    return r;
end $$;

create or replace function public.claim_global_mail(p_id bigint)
returns jsonb language plpgsql security definer set search_path = public as $$
declare r jsonb;
begin
    select rewards into r from public.global_mail where id = p_id;
    if r is null then raise exception 'mail not found'; end if;
    insert into public.global_mail_claims (user_id, mail_id) values (auth.uid(), p_id);
    return r;
exception when unique_violation then
    raise exception 'already claimed';
end $$;

grant execute on function public.claim_mail(bigint) to authenticated;
grant execute on function public.claim_global_mail(bigint) to authenticated;
